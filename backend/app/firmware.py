"""Canonical firmware configuration generated from a machine profile.

The configuration ID fingerprints exactly the values compiled into the
firmware. The machine shows it on its Info screen and boot serial line, so an
operator can prove the flashed firmware matches a recorded profile. Generation
never verifies hardware and never uploads anything.
"""

import hashlib
import json
import re
import zlib

from .drawing.errors import DrawingError

FIRMWARE_VERSION = "0.6.1"
FIRMWARE_DIALECT = "picasso-fw-v1"
CONFIG_SCHEMA = 1
CONFIG_FILENAME = "machine_config.h"
FLOATS = ("separation_mm", "anchor_y_mm", "spool_diameter_mm")
INTEGERS = ("steps_per_turn", "pen_up_degrees", "pen_down_degrees")
REGION = ("min_x_mm", "max_x_mm", "min_y_mm", "max_y_mm", "margin_mm")


def settings(profile) -> dict:
    """Firmware-relevant values only; labels, notes and attestations are excluded."""
    values = {name: float(getattr(profile, name)) for name in FLOATS}
    values.update({name: int(getattr(profile, name)) for name in INTEGERS})
    region = getattr(profile, "allowed_region", None)
    values["allowed_region"] = {name: float(getattr(region, name)) for name in REGION} if region else None
    values["rope_min_mm"] = float(profile.rope_min_mm) if region else None
    values["rope_max_mm"] = float(profile.rope_max_mm) if region else None
    return values


def config_id(profile) -> str:
    document = json.dumps({"schema": CONFIG_SCHEMA, "settings": settings(profile)}, sort_keys=True, separators=(",", ":"))
    return hashlib.sha256(document.encode()).hexdigest()[:16]


def gcode_crc32(code: str) -> str:
    """CRC-32 the firmware displays after validating main.nc."""
    return f"{zlib.crc32(code.encode('ascii')):08x}"


def _float(value: float) -> str:
    return f"({float(value)!r}f)"


def render(profile, *, kind: str) -> str:
    values = settings(profile)
    region = values["allowed_region"]
    if region is not None:
        from .storage.preparation import validate_point
        try:
            validate_point((0, 0), profile)
        except DrawingError as exc:
            raise DrawingError("FIRMWARE_CONFIG_INVALID", "The margin-adjusted workspace must contain the (0,0) origin below the anchor line before firmware can be generated.") from exc
    label = re.sub(r"[^ -~]", "?", profile.label)[:80]
    identity = getattr(profile, "id", "unsaved")
    version = getattr(profile, "version", None)
    lines = [
        f"// Generated by Project Picasso {FIRMWARE_VERSION} from the {kind} profile",
        f"// \"{label}\" ({identity}{f' v{version}' if version else ''}).",
        "// Do not edit. Regenerate: python3 scripts/firmware.py config (firmware/README.md).",
        "// Values are operator-recorded or source references; generating this file does",
        "// not verify the machine. Commission it before trusting any drawing.",
        "#ifndef PICASSO_MACHINE_CONFIG_H",
        "#define PICASSO_MACHINE_CONFIG_H",
        "",
        f"#define PICASSO_CONFIG_SCHEMA {CONFIG_SCHEMA}",
        f"#define PICASSO_CONFIG_ID \"{config_id(profile)}\"",
        f"#define PICASSO_SEPARATION_MM {_float(values['separation_mm'])}",
        f"#define PICASSO_ANCHOR_Y_MM {_float(values['anchor_y_mm'])}",
        f"#define PICASSO_SPOOL_DIAMETER_MM {_float(values['spool_diameter_mm'])}",
        f"#define PICASSO_STEPS_PER_TURN {values['steps_per_turn']}L",
        f"#define PICASSO_PEN_UP_DEGREES {values['pen_up_degrees']}",
        f"#define PICASSO_PEN_DOWN_DEGREES {values['pen_down_degrees']}",
    ]
    if region is None:
        lines += ["", "// No measured workspace: SD jobs, the test square and go-to-origin are disabled.",
                  "#define PICASSO_HAS_REGION 0"]
    else:
        lines += ["", "#define PICASSO_HAS_REGION 1"]
        lines += [f"#define PICASSO_REGION_{name.removesuffix('_mm').upper()}_MM {_float(region[name])}" for name in REGION]
        lines += [f"#define PICASSO_ROPE_MIN_MM {_float(values['rope_min_mm'])}",
                  f"#define PICASSO_ROPE_MAX_MM {_float(values['rope_max_mm'])}"]
    lines += ["", "#endif", ""]
    return "\n".join(lines)
